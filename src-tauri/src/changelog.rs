//! Release log "What's new": data is baked into the binary.
//!
//! ## Entry format (developer documentation)
//!
//! Each entry is a `ChangelogEntry` with fields:
//! - `version` — a string like "X.Y.Z"
//! - `date` — release date "DD.MM.YYYY"
//! - `gameplay` — an array of detailed descriptions of gameplay-affecting changes
//! - `fixes` — an array of short lines about bugfixes and improvements
//!
//! ### Gameplay formatting rules
//!
//! 1. **Each bullet is a separate feature**, do not duplicate the same thing.
//! 2. **Starts with an emoji** — a visual category marker:
//!    ⚔ combat, 🎯 skills/stats, 🤝 relationships, 📜 quests,
//!    🗺️ world, 👤 NPC, 🎁 items/inventory, 🏪 trade,
//!    🎉 interface, 📊 progress/leveling, 💬 dialogues.
//! 3. **First line** — a short feature name (up to ~80 characters).
//! 4. **Then** — a description of how it works, using a player example:
//!    what to do, what you will see, what will change. Without technical details.
//! 5. **Length** — 3–8 lines per feature. Not "in three words", but not an essay either.
//! 6. **Language** — conversational, like explaining to a friend. Not API documentation.
//!
//! ### Fixes formatting rules
//!
//! 1. **Briefly**: "Fixed N bugs, M tests." — that is enough.
//! 2. **If the improvement is visible to the player** — one line with an emoji.
//! 3. **Do not spell out** specific bugs — players are not interested.

use serde::{Deserialize, Serialize};


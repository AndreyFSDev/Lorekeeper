#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn changelog_not_empty_and_latest_is_first() {
        let log = changelog();
        assert!(!log.is_empty(), "changelog не должен быть пустым");
        assert_eq!(
            log[0].version, env!("CARGO_PKG_VERSION"),
            "первая запись должна соответствовать текущей версии Cargo.toml"
        );
    }

    #[test]
    fn versions_sorted_descending() {
        let log = changelog();
        for pair in log.windows(2) {
            let a: Vec<u32> = pair[0].version.split('.').map(|s| s.parse().unwrap()).collect();
            let b: Vec<u32> = pair[1].version.split('.').map(|s| s.parse().unwrap()).collect();
            assert!(
                a >= b,
                "версии должны идти от новой к старой: {} > {}",
                pair[0].version,
                pair[1].version
            );
        }
    }

    #[test]
    fn all_entries_have_dates() {
        let log = changelog();
        for entry in &log {
            assert!(
                !entry.date.is_empty(),
                "версия {} без даты",
                entry.version
            );
        }
    }
}




export type LocaleMode = 'auto' | Locale;

const STORAGE_KEY = 'cloufam.locale';

/** System language. `navigator.language` is not suitable: the window is given `--lang=ru-RU`
 * for the Russian SillyTavern, so the Windows language is supplied by a Rust init script. */
export function systemLocale(): Locale {
  const fromWindows = (window as { __LK_SYSTEM_LOCALE__?: string }).__LK_SYSTEM_LOCALE__;
  const primary = fromWindows ?? navigator.languages?.[0] ?? navigator.language ?? '';
  return primary.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

// WebView storage may be unavailable (read-only profile): the choice then
// lives until restart, and the language is taken from the system.
function readMode(): LocaleMode {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ru' || saved === 'en') return saved;
  } catch {}
  return 'auto';
}

function writeMode(mode: LocaleMode) {
  try {
    if (mode === 'auto') localStorage.removeItem(STORAGE_KEY);
    else localStorage.setItem(STORAGE_KEY, mode);
  } catch {}
}

class I18n {
  mode = $state<LocaleMode>(readMode());
  locale = $derived<Locale>(this.mode === 'auto' ? systemLocale() : this.mode);

  constructor() {
    this.pushLocale();
    // The settings window is a separate WebView of the same origin: the `storage`
    // event arrives in the other window's UI thread and switches the language without a restart.
    window.addEventListener('storage', (e) => {
      if (e.key === STORAGE_KEY || e.key === null) {
        this.mode = readMode();
        this.pushLocale();
      }
    });
  }

  // Rust returns window strings (boot statuses, model showcase, guide)
  // in the UI language — we send it the current locale at window start and
  // on every change. Swallow a refusal silently: the window language switches anyway.
  private pushLocale() {
    void invoke('set_locale', { lang: this.locale }).catch(() => {});
  }

  t(key: Key, vars?: Record<string, string | number>): string {
    const text = (this.locale === 'ru' ? ru : en)[key] ?? key;
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
  }

  setMode(mode: LocaleMode) {
    this.mode = mode;
    writeMode(mode);
    this.pushLocale();
  }
}

export const i18n = new I18n();
export const t = (key: Key, vars?: Record<string, string | number>) => i18n.t(key, vars);
export type { Key as I18nKey };



